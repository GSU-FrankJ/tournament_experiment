#!/usr/bin/env python3
"""T3-R1 P3: the ledger of the independent fact-check of the results reports (``pi_record/01_factcheck.md``).

Reads the stored results of the checkers (``results/t3_r1/factcheck/round{1,2}.json``: the workflow outputs, each with the checkers'
coverage notes, the problems that a skeptic confirmed and those it did not) and the author's dispositions (``DISPOSITIONS``: one entry
per confirmed problem of round 1; round 2 problems are listed with the text of the file ``factcheck/round2_dispositions.json``).

Usage:
    python reports/t3/r1/report_scripts/factcheck_ledger.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[4]
FC = ROOT / "results" / "t3_r1" / "factcheck"
OUT = ROOT / "reports" / "t3" / "r1" / "pi_record" / "01_factcheck.md"


def short(text: str, n: int = 150) -> str:
    """One line of at most n characters, without table pipes."""
    t = " ".join(str(text).split()).replace("|", "/")
    return t if len(t) <= n else t[: n - 3] + "..."


def tasks_table(tasks: List[Dict[str, object]]) -> str:
    """The checkers of a round."""
    lines = ["| checker | assignment | claims checked | problems reported |", "|---|---|---|---|"]
    for t in tasks:
        lines.append(f"| {t['key']} | {short(t['title'], 110)} | {int(t['claims_checked'])} | {t['n_findings']} |")
    lines.append(f"| all | {len(tasks)} checkers | {sum(int(t['claims_checked']) for t in tasks)} | {sum(t['n_findings'] for t in tasks)} |")
    return "\n".join(lines) + "\n"


def problems_table(items: List[Dict[str, object]], disp: Dict[int, str], default: str) -> str:
    """The confirmed problems with the disposition."""
    lines = ["| # | checker | kind | where | what the report said | what is true (checker, confirmed by a skeptic) | disposition |", "|---|---|---|---|---|---|---|"]
    for i, f in enumerate(items):
        lines.append(f"| {i} | {f['task']} | {f['severity']} | {short(f['location'], 70)} | {short(f['claim'], 110)} | {short(f['truth'], 190)} | {disp.get(i, default)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the ledger."""
    r1 = json.loads((FC / "round1.json").read_text())
    r2p = FC / "round2.json"
    d1 = {int(k): v for k, v in json.loads((FC / "round1_dispositions.json").read_text()).items()}
    out = ["# T3-R1: ledger of the independent fact-check of the results reports", "",
           "The check is read-only and independent: each checker re-derived the numbers of its part of `04_t3_results.md`, `05_t2_comparison.md`, `06_decision_inputs.md` and `summary.md` (and of the tables generated by `report_scripts/results_tables.py`) from the primary files of `results/t3_r1/` with its own code, and checked the coverage of D6 and D7; every problem a checker reported was re-derived by a second agent that tried to refute it. The results of the checkers are stored in `results/t3_r1/factcheck/` (`round1.json`, `round2.json`). Corrections were made in the templates and the table script (`report_scripts/`) and the reports were reassembled before the push.", "",
           "## Round 1 (on the first assembled reports)", "", tasks_table(r1["tasks"]),
           f"{len(r1['confirmed'])} problems were confirmed by the second agent and {len(r1['not_confirmed'])} were not. All confirmed problems were corrected (no number of the data changed; the reports' prose, the tables' labels, and missing D6 / D7 elements were fixed):", "",
           problems_table(r1["confirmed"], d1, "corrected"), "",
           "Reported but not confirmed by the second agent (no change):", ""]
    for f in r1["not_confirmed"]:
        out.append(f"- {f['task']}, {f['severity']}, {short(f['location'], 80)}: {short(f['claim'], 140)} - not confirmed: {short(f['why_not_confirmed'], 260)}")
    out.append("")
    if r2p.exists():
        r2 = json.loads(r2p.read_text())
        d2p = FC / "round2_dispositions.json"
        d2 = {int(k): v for k, v in json.loads(d2p.read_text()).items()} if d2p.exists() else {}
        out += ["## Round 2 (on the corrected reports)", "", tasks_table(r2["tasks"]),
                f"{len(r2['confirmed'])} problems were confirmed and {len(r2['not_confirmed'])} were not.", ""]
        if r2["confirmed"]:
            out += [problems_table(r2["confirmed"], d2, "corrected"), ""]
        out.append("Reported but not confirmed (no change):")
        out.append("")
        for f in r2["not_confirmed"]:
            out.append(f"- {f['task']}, {f['severity']}, {short(f['location'], 80)}: {short(f['claim'], 140)} - not confirmed: {short(f['why_not_confirmed'], 260)}")
        out.append("")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
