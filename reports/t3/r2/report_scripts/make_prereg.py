#!/usr/bin/env python3
"""Writes ``reports/t3/r2/02_preregistration.md`` (P1): D4 and D5 verbatim from the stored prompt, the operating-characteristic
table, the planned 40 configs with their SHA-256 and planned init digests, the config difference to T3-R1's ``bw`` per q, the lock
drafts with their SHA-256, the seed inventory and the launch plan.

Inputs (all committed before this file): ``pi_record/27_t3_r2_prompt.md``, ``tables/t01_operating_characteristic.md``
(``oc_table.py``), ``confirmation_plan.csv`` (``tools/t3/t3c_launch.py --plan-csv``), ``lock_draft/`` (``tools/t3/t3r2_make_lock.py``),
``results/t3_r2/preflight/seed_*``.

Usage:
    python reports/t3/r2/report_scripts/make_prereg.py
"""

from __future__ import annotations

import csv
import hashlib
import json
import re
from pathlib import Path

from common import REP, RES, ROOT, md

import t3_configs as tc  # noqa: E402
import t3c_launch as cl  # noqa: E402


def sha(p: Path) -> str:
    """SHA-256 of a file."""
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def section(text: str, start: str, end: str) -> str:
    """The text from the heading ``start`` up to (not including) the heading ``end``."""
    i = text.index(start)
    j = text.index(end, i + len(start))
    return text[i:j].rstrip() + "\n"


def main() -> int:
    """Assemble the pre-registration."""
    prompt = (REP / "pi_record" / "27_t3_r2_prompt.md").read_text()
    d4 = section(prompt, "### D4. The confirmation", "### D5. Predictions")
    d5 = section(prompt, "### D5. Predictions", "### D6. Reference roots")
    oc = (REP / "tables" / "t01_operating_characteristic.md").read_text()
    plan = list(csv.DictReader(open(REP / "confirmation_plan.csv")))
    lock_dir = REP / "lock_draft"
    lock = json.loads((lock_dir / "v2_T3_locked_v1_0.json").read_text())
    proto, params = tc.load_protocol(), tc.load_bw_params()
    diffs = {}
    for q in cl.QS:
        recorded = json.loads((ROOT / "results" / "t3_r1" / "runs" / f"q{q}" / "seed50501" / "bw" / "run_config.json").read_text())
        cfg = cl.build_confirmation_config(proto, q, 60501, "OUT", params)
        diffs[q] = (tc.config_diff(cfg, recorded), tc.config_diff(cl.build_confirmation_config(proto, q, 60520, "OUT", params), recorded))
    seeds_out = (RES / "preflight" / "seed_inventory_60501_60520.out.txt").read_text()
    hits = list(csv.DictReader(open(RES / "preflight" / "seed_hits_60501_60520.csv")))
    plan_rows = [(r["run"], r["q"], r["seed"], f"`{r['run_config_sha256_relpath'][:16]}...`", f"`{r['init_state_sha256'][:16]}...`") for r in plan]
    lines = [
        "# T3-R2, pre-registration of the T = 3 confirmation", "",
        "Written and committed in P1, before any confirmation run. The settings are those of T3-R1's `bw` arm, unchanged; nothing "
        "below is tuned. The decisions D4 and D5 are copied verbatim from the PI's prompt (`pi_record/27_t3_r2_prompt.md`); the "
        "lock drafts and the plan are generated by the tools named in each section.", "",
        "## 1. The confirmation (D4, verbatim)", "", d4, "## 2. Predictions (D5, verbatim)", "", d5,
        "## 3. Operating characteristic of the rule", "",
        "Per-run pass probability p, the same at both q and independent between the q blocks; the confirmation passes iff "
        "X50 >= 17, X60 >= 17 and X50 + X60 >= 36 with X_q ~ Binomial(20, p). Generated by `report_scripts/oc_table.py` "
        "(`results/t3_r2/preflight/oc_table.csv`):", "", oc,
        "## 4. The planned 40 configs", "",
        "`reports/t3/r2/confirmation_plan.csv` (from `python tools/t3/t3c_launch.py --plan-csv reports/t3/r2/confirmation_plan.csv`) "
        "holds, for every run, the run name, the output directory, the SHA-256 of the `run_config.json` as written and with the output "
        "directory made relative (the hash the post-launch check compares) and the planned init digest (the run constructed without "
        "training, `MSRun.init_state_sha256`). The table gives the first 16 hex digits.", "",
        md(["run", "q", "seed", "config SHA-256 (relative output directory)", "planned init digest"], plan_rows),
        "## 5. Difference to T3-R1's `bw` configs", "",
        "`t3_configs.config_diff` of a confirmation config against the config T3-R1 recorded for the same q (seed 50501, "
        "`results/t3_r1/runs/q{q}/seed50501/bw/run_config.json`):", "",
        md(["q", "paths in which the configs differ (seed 60501)", "paths in which the configs differ (seed 60520)"],
           [(q, ", ".join(f"`{p}`" for p in d[0]), ", ".join(f"`{p}`" for p in d[1])) for q, d in diffs.items()]),
        f"Allowed by D4: {', '.join(f'`{f}`' for f in cl.ALLOWED_DIFF)}. The launcher additionally refuses any config whose "
        "normalised form (those fields reset to the reference run) does not hash to `reference_config_sha256` of the lock; "
        "`tests/test_t3r2_launch.py` tests both.", "",
        "## 6. The lock drafts", "",
        "`tools/t3/t3r2_make_lock.py --out reports/t3/r2/lock_draft/`. The files hold no timestamp, no commit hash and no absolute "
        "path; P2 writes `protocols/v2_T3_locked_v1_0.{json,md}` with the same tool and they must equal the drafts byte for byte.", "",
        md(["file", "SHA-256"], [(f"`lock_draft/{n}`", f"`{sha(lock_dir / n)}`") for n in ("v2_T3_locked_v1_0.json", "v2_T3_locked_v1_0.md")]),
        "Tool files the lock fixes (the launcher refuses if one differs):", "",
        md(["tool file", "SHA-256"], [(f"`{f}`", f"`{h}`") for f, h in lock["tool_sha256"].items()]),
        f"Parameters file `{lock['params_file']}`: `{lock['params_sha256']}`; protocol file `{lock['protocol_file']}`: "
        f"`{lock['protocol_sha256']}`; criteria `{lock['criteria_file']}`: `{lock['criteria_sha256']}`.", "",
        "## 7. Seed inventory (P0.3)", "",
        "```", seeds_out.strip(), "```", "",
        f"`results/t3_r2/preflight/seed_hits_60501_60520.csv` has {len(hits)} hit rows. No file of any class records a seed of "
        "60501-60520: the block is unused. (Seeds never trained and not used: 40501-40520, 10501-10530, 30501-30520, 50500-50520 "
        "except the four audit re-runs of A1.)", "",
        "## 8. Launch plan", "",
        "- 40 runs (`bw`, q in {50, 60}, seeds 60501-60520), wave `t3c`, at most 40 single-threaded workers "
        "(`OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1`), in tmux, from the commit that holds the LOCK record, on a "
        "clean tree: `python tools/t3/t3c_launch.py --workers 40 --code-commit <lock commit>`.",
        "- Recorded at launch: `nproc`, load, free disk, HEAD, `git status --porcelain` and `git diff --stat be2b7e9f HEAD -- agents envs utils "
        "run tools/ms tools/v2` (must be empty; under `tools/t3/` only new `t3c_*` and `t3r2_*` files); the launcher refuses otherwise.",
        "- Expected cost: about 10 minutes per run (T3-R1's `bw`: median 578 s, `results/t3_r1/analysis/cost.csv`), so the wave takes "
        "about 10 to 15 minutes of wall time with 40 workers on a free machine; the final evaluation of the 40 runs a few minutes more.",
        "- After the launch: `t3c_checks.py` (`launch_checks.json`), `t3c_eval.py`, `t3c_analysis.py --diagnose`, `t3c_blind.py` "
        "(the counts and the verdict must agree with the analysis); the infrastructure rule of D4 applies throughout.",
        "- P2 starts only after the PI's reply \"proceed P2\" at gate G1. If the audit finds an implementation error there is no P2 "
        "in this round.", ""]
    (REP / "02_preregistration.md").write_text("\n".join(lines))
    print(f"wrote {REP / '02_preregistration.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
