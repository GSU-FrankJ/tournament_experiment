"""
Monte Carlo + Finite-Difference (MC-FD) solver with Common Random Numbers (CRN)
for two-player noisy effort competitions.

This module purposefully avoids analytic probability formulas. Instead, it
estimates gradients of the expected payoff via simulation, finite differences,
and CRN variance reduction.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Tuple, Optional

import numpy as np


@dataclass
class MCFDConfig:
    """
    Configuration for the MC-FD solver.

    Attributes focus on commonly tuned hyper-parameters and payoff constants.
    """

    w_h: float = 30.0
    w_l: float = 15.0
    k: float = 0.002
    sigma1: float = 20.0
    sigma2: float = 20.0
    delta: float = 0.1  # Finite-difference perturbation magnitude
    eta: float = 0.05  # Gradient-ascent learning rate
    num_samples: int = 5000  # Monte Carlo sample size per gradient estimate
    e_min: float = 0.0
    e_max: float = 100.0
    max_iters: int = 500
    tol: float = 1e-3
    seed: Optional[int] = 0
    effort_range: Tuple[float, float] = field(init=False)

    def __post_init__(self) -> None:
        """Normalize bounds once to simplify later clipping logic."""
        self.effort_range = (float(self.e_min), float(self.e_max))
        if self.delta <= 0:
            raise ValueError("delta must be positive for finite differences")
        if self.num_samples <= 0:
            raise ValueError("num_samples must be positive")
        if self.max_iters <= 0:
            raise ValueError("max_iters must be positive")


def clip_effort(value: float, bounds: Tuple[float, float]) -> float:
    """
    Clamp effort values to the feasible interval.

    A dedicated helper keeps the gradient update logic readable.
    """

    lo, hi = bounds
    return max(lo, min(hi, value))


def simulate_payoff(
    e1: float,
    e2: float,
    eps1: float,
    eps2: float,
    w_h: float,
    w_l: float,
    k: float,
) -> Tuple[float, float]:
    """
    Simulate a single-shot payoff for both players using supplied Gaussian noise.

    Args:
        e1, e2: Efforts for players 1 and 2 (already clipped).
        eps1, eps2: Noise draws for players 1 and 2 (CRN friendly).
        w_h, w_l: Prize values for winner and loser.
        k: Quadratic effort cost coefficient.

    Returns:
        Tuple of payoffs (u1, u2) generated by comparing noisy outputs.
    """

    y1 = e1 + eps1
    y2 = e2 + eps2

    if y1 > y2:
        payoff1, payoff2 = w_h, w_l
    elif y2 > y1:
        payoff1, payoff2 = w_l, w_h
    else:
        # Ties are broken fairly via expected value split.
        payoff1 = payoff2 = 0.5 * (w_h + w_l)

    u1 = payoff1 - k * (e1 ** 2)
    u2 = payoff2 - k * (e2 ** 2)
    return u1, u2


def estimate_gradient_for_player(
    player_index: int,
    e_self: float,
    e_other: float,
    sigma_self: float,
    sigma_other: float,
    cfg: MCFDConfig,
    rng: np.random.Generator,
) -> Tuple[float, Dict[str, float]]:
    """
    Estimate the gradient of player-index payoff via MC-FD with CRN.

    Args:
        player_index: 0 for player 1, 1 for player 2.
        e_self, e_other: Current efforts.
        sigma_self, sigma_other: Standard deviations for noise.
        cfg: Shared MC-FD configuration.
        rng: Random generator dedicated to this player (guarantees CRN).

    Returns:
        (gradient_estimate, diagnostics) where diagnostics collects averages.
    """

    e_plus = clip_effort(e_self + cfg.delta, cfg.effort_range)
    e_minus = clip_effort(e_self - cfg.delta, cfg.effort_range)

    # Generate the CRN noise batch once; reuse for +delta and -delta evaluations.
    eps_self = rng.normal(loc=0.0, scale=sigma_self, size=cfg.num_samples)
    eps_other = rng.normal(loc=0.0, scale=sigma_other, size=cfg.num_samples)

    payoffs_plus = np.empty(cfg.num_samples, dtype=float)
    payoffs_minus = np.empty(cfg.num_samples, dtype=float)

    for idx in range(cfg.num_samples):
        if player_index == 0:
            # Player 1 perturbed; opponent stays at current effort.
            u_plus, _ = simulate_payoff(
                e_plus, e_other, eps_self[idx], eps_other[idx], cfg.w_h, cfg.w_l, cfg.k
            )
            u_minus, _ = simulate_payoff(
                e_minus, e_other, eps_self[idx], eps_other[idx], cfg.w_h, cfg.w_l, cfg.k
            )
        else:
            # Player 2 perturbed; player 1 effort held fixed.
            _, u_plus = simulate_payoff(
                e_other, e_plus, eps_other[idx], eps_self[idx], cfg.w_h, cfg.w_l, cfg.k
            )
            _, u_minus = simulate_payoff(
                e_other, e_minus, eps_other[idx], eps_self[idx], cfg.w_h, cfg.w_l, cfg.k
            )
        payoffs_plus[idx] = u_plus
        payoffs_minus[idx] = u_minus

    avg_plus = float(payoffs_plus.mean())
    avg_minus = float(payoffs_minus.mean())
    gradient = (avg_plus - avg_minus) / (2.0 * cfg.delta)

    diagnostics = {
        "avg_u_plus": avg_plus,
        "avg_u_minus": avg_minus,
        "gradient": gradient,
    }
    return gradient, diagnostics


def gradient_ascent_dynamics(
    cfg: MCFDConfig,
    rng: Optional[np.random.Generator] = None,
) -> Dict[str, List[float]]:
    """
    Run simultaneous gradient-ascent dynamics for both players.

    Args:
        cfg: MC-FD configuration containing payoffs, bounds, and hyper-parameters.
        rng: Optional pre-seeded generator for deterministic experiments.

    Returns:
        Dictionary containing effort histories, gradient logs, and diagnostics.
    """

    base_rng = rng or np.random.default_rng(cfg.seed)
    e1 = base_rng.uniform(cfg.e_min, cfg.e_max)
    e2 = base_rng.uniform(cfg.e_min, cfg.e_max)
    # Enforce distinct initial efforts to avoid trivial symmetric starts.
    if abs(e1 - e2) < 1e-8:
        e2 = clip_effort(e2 + 0.1, cfg.effort_range)

    history_e1: List[float] = [e1]
    history_e2: List[float] = [e2]
    grad_history: List[Tuple[float, float]] = []
    payoff_history: List[Tuple[float, float]] = []

    for iteration in range(cfg.max_iters):
        grad_rng1 = np.random.default_rng(base_rng.integers(0, 2**32 - 1))
        grad_rng2 = np.random.default_rng(base_rng.integers(0, 2**32 - 1))

        g1, diag1 = estimate_gradient_for_player(
            player_index=0,
            e_self=e1,
            e_other=e2,
            sigma_self=cfg.sigma1,
            sigma_other=cfg.sigma2,
            cfg=cfg,
            rng=grad_rng1,
        )
        g2, diag2 = estimate_gradient_for_player(
            player_index=1,
            e_self=e2,
            e_other=e1,
            sigma_self=cfg.sigma2,
            sigma_other=cfg.sigma1,
            cfg=cfg,
            rng=grad_rng2,
        )

        e1_new = clip_effort(e1 + cfg.eta * g1, cfg.effort_range)
        e2_new = clip_effort(e2 + cfg.eta * g2, cfg.effort_range)

        grad_history.append((g1, g2))
        payoff_history.append((diag1["avg_u_plus"], diag2["avg_u_plus"]))
        history_e1.append(e1_new)
        history_e2.append(e2_new)

        delta_e1 = abs(e1_new - e1)
        delta_e2 = abs(e2_new - e2)

        e1, e2 = e1_new, e2_new

        if delta_e1 < cfg.tol and delta_e2 < cfg.tol:
            break

    return {
        "effort_player1": history_e1,
        "effort_player2": history_e2,
        "gradients": grad_history,
        "payoffs_plus": payoff_history,
    }


if __name__ == "__main__":
    default_cfg = MCFDConfig(
        w_h=30.0,
        w_l=15.0,
        k=0.002,
        sigma1=20.0,
        sigma2=20.0,
        delta=1.0,
        eta=0.1,
        num_samples=64,
        e_min=0.0,
        e_max=100.0,
        max_iters=300,
        tol=1e-3,
        seed=1234,
    )
    results = gradient_ascent_dynamics(default_cfg)
    print("Final player efforts:")
    print(f"e1 -> {results['effort_player1'][-1]:.3f}")
    print(f"e2 -> {results['effort_player2'][-1]:.3f}")
    print(f"Iterations: {len(results['effort_player1']) - 1}")
