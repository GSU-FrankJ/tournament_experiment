#!/usr/bin/env python3
"""
Generate INVENTORY.md showing experiment coverage matrix.

Scans all results/*/convergence/ and results/ablation/*/runs/ directories
to build a coverage matrix showing what's been run vs what's missing.

Usage:
    python tools/generate_inventory.py
    python tools/generate_inventory.py --output INVENTORY.md
"""

from __future__ import annotations

import argparse
import json
import os
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple


ROOT = Path(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RESULTS_DIR = ROOT / "results"

EXPERIMENTS = ["two_players", "three_players", "different_cost", "different_ability"]
Q_VALUES = [25.0, 40.0, 55.0]
SEEDS = [42, 123, 456]

EXPLOIT_SETTINGS = [
    "baseline", "eps_001", "eps_003", "eps_010", "eps_020",
    "pat_01", "pat_03", "pat_10",
]

MECHANISM_SETTINGS = [
    "baseline", "no_cheap_gate", "no_exploit", "no_entropy",
]


def scan_convergence_files(experiment: str) -> Dict[Tuple[float, int, str], str]:
    """Scan convergence directory for an experiment and return (q, seed, ablation) -> filepath."""
    conv_dir = RESULTS_DIR / experiment / "convergence"
    found = {}

    if not conv_dir.exists():
        return found

    for f in conv_dir.iterdir():
        if not f.name.endswith("_convergence.json"):
            continue

        # Parse filename to extract q, seed, ablation
        base = f.name.replace("_convergence.json", "")

        # Strip experiment prefix
        if experiment == "different_cost":
            base = base.replace("different_cost_", "", 1)
        elif experiment == "different_ability":
            base = base.replace("different_ability_", "", 1)
        elif experiment == "three_players":
            base = base.replace("ppo_3p_", "ppo_", 1)  # normalize

        # Match: {method}_q{q}_seed{seed}[_{ablation}]
        m = re.match(r"^(?:ppo|gradient)_q([\d.]+)_seed(\d+)(?:_(.+))?$", base)
        if m:
            q = float(m.group(1))
            seed = int(m.group(2))
            ablation = m.group(3) if m.group(3) else "baseline"
            found[(q, seed, ablation)] = str(f)
            continue

        # Legacy: {method}_q{q}
        m = re.match(r"^(?:ppo|gradient)_q([\d.]+)$", base)
        if m:
            q = float(m.group(1))
            found[(q, 42, "baseline")] = str(f)

    return found


def scan_ablation_runs(ablation_type: str) -> Dict[Tuple[str, float, int, str], str]:
    """Scan ablation runs directory. Returns (experiment, q, seed, setting) -> filepath."""
    runs_dir = RESULTS_DIR / "ablation" / ablation_type / "runs"
    found = {}

    if not runs_dir.exists():
        return found

    for f in runs_dir.iterdir():
        if not f.name.endswith(".json"):
            continue

        try:
            with open(f) as fh:
                data = json.load(fh)
            exp = data.get("experiment", "")
            q = float(data.get("q", 0))
            seed = int(data.get("seed", 0))
            setting = data.get("setting_id", "")
            if exp and q and seed and setting:
                found[(exp, q, seed, setting)] = str(f)
        except Exception:
            pass

    return found


def build_coverage_table(
    experiment: str,
    found: Dict[Tuple[float, int, str], str],
    settings: List[str],
) -> List[str]:
    """Build a markdown coverage table for one experiment."""
    lines = []

    # Header
    header = "| q | seed |"
    separator = "|---|------|"
    for s in settings:
        header += f" {s} |"
        separator += f"{'---':->5}|"

    lines.append(header)
    lines.append(separator)

    completed = 0
    total = 0

    for q in Q_VALUES:
        for seed in SEEDS:
            row = f"| {q:.0f} | {seed} |"
            for s in settings:
                total += 1
                if (q, seed, s) in found:
                    row += " Y |"
                    completed += 1
                else:
                    row += " - |"
            lines.append(row)

    return lines, completed, total


def generate_inventory(output_path: str) -> None:
    """Generate the INVENTORY.md file."""
    lines = [
        "# Experiment Inventory",
        "",
        f"Auto-generated by `tools/generate_inventory.py`",
        "",
    ]

    grand_completed = 0
    grand_total = 0

    # Per-experiment convergence coverage
    for experiment in EXPERIMENTS:
        title = experiment.replace("_", " ").title()
        lines.append(f"## {title}")
        lines.append("")

        found = scan_convergence_files(experiment)

        # Determine which settings appear
        all_ablations = sorted({abl for (_, _, abl) in found.keys()})
        if not all_ablations:
            all_ablations = ["baseline"]

        # Use exploit settings if they appear, otherwise just baseline
        settings = EXPLOIT_SETTINGS if len(all_ablations) > 1 else ["baseline"]

        table_lines, completed, total = build_coverage_table(experiment, found, settings)
        for tl in table_lines:
            lines.append(tl)

        lines.append("")
        lines.append(f"Coverage: {completed}/{total} ({100*completed/total:.0f}%)" if total > 0 else "No runs found.")
        lines.append("")

        grand_completed += completed
        grand_total += total

    # Exploit ablation coverage
    lines.append("## Exploit Parameter Ablation")
    lines.append("")

    exploit_runs = scan_ablation_runs("exploit_params")
    if exploit_runs:
        for experiment in EXPERIMENTS:
            exp_runs = {(q, s, st): p for (e, q, s, st), p in exploit_runs.items() if e == experiment}
            if not exp_runs:
                continue

            title = experiment.replace("_", " ").title()
            lines.append(f"### {title}")
            lines.append("")

            header = "| q | seed |"
            separator = "|---|------|"
            for s in EXPLOIT_SETTINGS:
                header += f" {s} |"
                separator += f"{'---':->5}|"
            lines.append(header)
            lines.append(separator)

            for q in Q_VALUES:
                for seed in SEEDS:
                    row = f"| {q:.0f} | {seed} |"
                    for s in EXPLOIT_SETTINGS:
                        if (q, seed, s) in exp_runs:
                            row += " Y |"
                        else:
                            row += " - |"
                    lines.append(row)

            lines.append("")
    else:
        lines.append("No exploit ablation runs found.")
        lines.append("")

    # Mechanism ablation coverage
    lines.append("## Mechanism Ablation (NEW - planned)")
    lines.append("")

    mechanism_runs = scan_ablation_runs("mechanism")
    if mechanism_runs:
        for experiment in EXPERIMENTS:
            exp_runs = {(q, s, st): p for (e, q, s, st), p in mechanism_runs.items() if e == experiment}
            if not exp_runs:
                continue

            title = experiment.replace("_", " ").title()
            lines.append(f"### {title}")
            lines.append("")

            header = "| q | seed |"
            separator = "|---|------|"
            for s in MECHANISM_SETTINGS:
                header += f" {s} |"
                separator += f"{'---':->5}|"
            lines.append(header)
            lines.append(separator)

            for q in Q_VALUES:
                for seed in SEEDS:
                    row = f"| {q:.0f} | {seed} |"
                    for s in MECHANISM_SETTINGS:
                        if (q, seed, s) in exp_runs:
                            row += " Y |"
                        else:
                            row += " - |"
                    lines.append(row)
            lines.append("")
    else:
        header = "| Experiment | q | seed |"
        separator = "|------------|---|------|"
        for s in MECHANISM_SETTINGS:
            header += f" {s} |"
            separator += f"{'---':->5}|"
        lines.append(header)
        lines.append(separator)

        for experiment in EXPERIMENTS:
            for q in Q_VALUES:
                for seed in SEEDS:
                    row = f"| {experiment} | {q:.0f} | {seed} |"
                    for s in MECHANISM_SETTINGS:
                        row += " - |"
                    lines.append(row)
        lines.append("")
        total_mechanism = len(EXPERIMENTS) * len(Q_VALUES) * len(SEEDS) * len(MECHANISM_SETTINGS)
        lines.append(f"Total planned: {total_mechanism} runs (0 completed)")
        lines.append("")

    # Summary
    lines.append("## Summary Statistics")
    lines.append("")
    lines.append(f"- Convergence runs completed: {grand_completed}")
    lines.append(f"- Convergence runs total: {grand_total}")
    lines.append(f"- Coverage: {grand_completed}/{grand_total} ({100*grand_completed/grand_total:.0f}%)" if grand_total > 0 else "- Coverage: N/A")

    exploit_count = len(exploit_runs)
    lines.append(f"- Exploit ablation runs: {exploit_count}")

    mechanism_count = len(mechanism_runs)
    total_mechanism = len(EXPERIMENTS) * len(Q_VALUES) * len(SEEDS) * len(MECHANISM_SETTINGS)
    lines.append(f"- Mechanism ablation runs: {mechanism_count}/{total_mechanism}")
    lines.append("")

    # Write output
    with open(output_path, "w") as f:
        f.write("\n".join(lines))

    print(f"Generated {output_path}")
    print(f"  Convergence: {grand_completed}/{grand_total}")
    print(f"  Exploit ablation: {exploit_count}")
    print(f"  Mechanism ablation: {mechanism_count}/{total_mechanism}")


def main():
    parser = argparse.ArgumentParser(description="Generate experiment inventory")
    parser.add_argument(
        "--output",
        default=str(ROOT / "INVENTORY.md"),
        help="Output file path (default: INVENTORY.md)",
    )
    args = parser.parse_args()
    generate_inventory(args.output)


if __name__ == "__main__":
    main()
